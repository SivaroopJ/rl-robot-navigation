"""Assemble results/week6_continuation/* into MD_files/week6_continuation/CONTINUATION_REPORT_DATA.md
and a combined machine-readable manifest. Read-only over the stage outputs."""
from __future__ import annotations

import json
from pathlib import Path

from continuation.harness import RESULTS
from experiments.week6_continuation.common import load_json, table

OUT_MD = Path("MD_files/week6_continuation/CONTINUATION_REPORT_DATA.md")
EXTRA = [("recovery_success_rate", "recOK"), ("P_event_collision_within_1s", "P(c<1s|ev)"),
         ("tier_frac_T0", "T0"), ("tier_frac_T1", "T1"), ("tier_frac_T2", "T2"),
         ("cbf_min_margin_worst", "minCBC"), ("clf_slack_mean", "slack"),
         ("action_norm_mean", "|u|"), ("mean_u_dev", "|u-unom|"), ("mean_path_length", "path"),
         ("infeasible_duration_mean", "dur")]
TIMING = [("step_time_ms_mean_ep", "mean ms"), ("step_time_ms_median_ep", "median ms"),
          ("step_time_ms_p95_ep", "p95 ms"), ("step_time_ms_worst", "worst ms"),
          ("qp_time_ms_mean", "QP ms"), ("recovery_overhead_ms_mean", "recov. ovh ms"),
          ("random_eval_ms_mean", "rand eval ms"), ("candidates_mean", "cands/event"),
          ("episode_time_s_mean", "episode s")]


def sect(title, body):
    return f"\n## {title}\n\n{body}\n"


def fmt_cmp(cmp, keys=("success", "collision", "dynamic_collision", "static_collision",
                       "wall_collision", "timeout")):
    rows = ["| cond | metric | diff | 95% CI | n10 | n01 | McNemar p |", "|---|---|---|---|---|---|---|"]
    for c in ("fixed", "randomized", "pooled"):
        for k in keys:
            v = cmp[c][k]
            rows.append(f"| {c} | {k} | {v['diff']:+.3f} | [{v['ci95'][0]:+.3f}, "
                        f"{v['ci95'][1]:+.3f}] | {v['only_a']} | {v['only_b']} | {v['p']:.4f} |")
        for k in ("min_clearance", "spl", "step_time_ms_mean", "mean_u_dev"):
            v = cmp[c][k]
            rows.append(f"| {c} | {k} | {v['diff']:+.4f} | [{v['ci95'][0]:+.4f}, "
                        f"{v['ci95'][1]:+.4f}] | | | bootstrap |")
        v = cmp[c]["infeasible_step_rate"]
        rows.append(f"| {c} | infeasible-step rate | {v['diff']:+.4f} | [{v['ci95'][0]:+.4f}, "
                    f"{v['ci95'][1]:+.4f}] | | | cluster bootstrap |")
    return "\n".join(rows)


def main():
    md = ["# Week 6 Continuation — generated result tables\n",
          "Generated by `experiments/week6_continuation/report.py` from `results/week6_continuation/`."]
    manifest = []
    for stage, tag in (("C0", "C0"), ("C1", "C1"), ("H1", "H1"), ("H2", "H2"),
                       ("RANDOM_EXP_R1", "RANDOM_EXP_R1"), ("RANDOM_EXP_R2", "RANDOM_EXP_R2"),
                       ("R3", "R3_screen"), ("R3", "R3_validation"), ("F", "F")):
        sp = RESULTS / stage / f"{tag}_summary.json"
        if not sp.exists():
            continue
        s = load_json(sp)["summary"]
        names = list(s)
        if tag in ("H1", "H2", "R3_screen"):
            md.append(sect(f"{tag} (pooled, all {len(names)} arms)", table(s, names, conds=("pooled",))))
        else:
            md.append(sect(f"{tag}: headline", table(s, names)))
            md.append(sect(f"{tag}: recovery / controller", table(s, names, keys=EXTRA)))
            md.append(sect(f"{tag}: timing", table(s, names, keys=TIMING)))
        mp = RESULTS / stage / f"{tag}_manifest.jsonl"
        manifest += [json.loads(l) for l in mp.read_text().splitlines()]
    fp = RESULTS / "F" / "F_paired.json"
    if fp.exists():
        f = load_json(fp)
        for lab, c in f["comparisons"].items():
            md.append(sect(f"F paired: {lab} ({c['x']} vs {c['y']}; + = first higher)",
                           fmt_cmp(c["result"])))
    OUT_MD.write_text("\n".join(md))
    mp = RESULTS / "MANIFEST_ALL.jsonl"
    mp.write_text("".join(json.dumps(r) + "\n" for r in manifest))
    print(f"wrote {OUT_MD} and {mp} ({len(manifest)} episode rows)")


if __name__ == "__main__":
    main()
